import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6.0
R_A = 170.0
R_B = 410.0
P_1 = 100.0
q_1 = 120.0
q_2 = 120.0

x = np.linspace(0, L, 500)
V = np.zeros_like(x)

for i in range(len(x)):
  xi = x[i]
  if xi < 2:
    V[i] = R_A - (q_1 * xi)
  elif 2 < xi < 4:
    V[i] = R_A - (q_1 * 2) - P_1
  elif xi > 4:
    V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (xi - 4))

plt.figure(figsize=(6, 5))
plt.plot(x, V, color="royalblue", linewidth=2.25)
plt.fill_between(x, V, 0, color="skyblue", alpha=0.5)
plt.title("Shear Diagram")
plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.axhline(0, color="black", linewidth=1)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6.0
R_A = 170.0
R_B = 410.0
P_1 = 100.0
q_1 = 120.0
q_2 = 120.0

x = np.linspace(0, L, 500)

M = np.zeros_like(x)

for i in range(len(x)):
  xi = x[i]
  if xi < 2:
    M[i] = (R_A * xi) - (q_1 * (xi**2) / 2)
  elif 2 < xi < 4:
    M[i] = (R_A * xi) - (q_1 * 2 * (xi - 1)) - (P_1 * (xi - 2))
  elif xi > 4:
    M[i] = (
        (R_A * xi)
        - (q_1 * 2 * (xi - 1))
        - (P_1 * (xi - 2))
        + (R_B * (xi - 4))
        - (q_2 * (xi - 4) * ((xi - 4) / 2))
    )

plt.figure(figsize=(6, 5))
plt.plot(x, M, color="royalblue", linewidth=2.5)

plt.fill_between(x, M, 0, color="deepskyblue", alpha=0.5)

plt.title("Moment Diagram")
plt.xlabel("x (ft)")
plt.ylabel("M (lb-ft)")
plt.axhline(0, color="black", linewidth=1)
plt.show()

