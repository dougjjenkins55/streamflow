plt.fill_between(df_daily['Date'], df_daily['Total'], color="#69969a", label="Fremont Bridge Total", alpha=0.7)
plt.fill_between(df_daily['Date'], df_daily['West'], color="#8b0000", label="Fremont Bridge West Sidewalk", alpha=0.9)
plt.fill_between(df_daily['Date'], df_daily['East'], color="#ff8c00", label="Fremont Bridge East Sidewalk", alpha=1.0)

plt.title("Fremont Bridge Bicycle Count (Daily Totals)")
plt.xlabel("Date")
plt.ylabel("Number of Bicycles")
plt.legend(loc="upper left")
plt.grid(True, linestyle="-", linewidth=0.5, alpha=0.7)

# The drop in bicycle counts during 2020 and 2021 is probably due to the COVID-19 pandemic

